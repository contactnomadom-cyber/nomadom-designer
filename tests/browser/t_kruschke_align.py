# Étape 4 : « Aligner la base » en Kruschke + refus quand des triangles se retourneraient
import sys, os
from playwright.sync_api import sync_playwright
APP = 'file://' + os.path.abspath(sys.argv[1])
fails = []
def check(c, m):
    print(('OK   ' if c else 'ÉCHEC ') + m)
    if not c: fails.append(m)
with sync_playwright() as p:
    b = p.chromium.launch(args=["--use-gl=swiftshader", "--enable-webgl", "--ignore-gpu-blocklist"])
    pg = b.new_page(viewport={'width': 1400, 'height': 1000})
    errs = []; pg.on('pageerror', lambda e: errs.append(str(e)))
    pg.goto(APP); pg.wait_for_timeout(1500)
    T = lambda s: pg.inner_text(s)
    def base(V, m, sym, part, align):
        pg.click('#tabBase'); pg.select_option('#paramDetail', V); pg.wait_for_timeout(200)
        pg.select_option('#paramMethod', m); pg.wait_for_timeout(200)
        pg.select_option('#paramSymmetry', sym); pg.wait_for_timeout(200)
        pg.select_option('#paramPartial', part); pg.wait_for_timeout(200)
        if pg.is_checked('#paramAlign') != align: pg.click('#paramAlign'); pg.wait_for_timeout(600)
        pg.fill('#paramDiameter', '5.00'); pg.click('#btnRegenerate'); pg.wait_for_timeout(1200)
    base('3', 'Kruschke', 'Pentad', '7/12', False)
    ref = T('#baseStruts')
    check(not pg.locator('#paramAlign').is_disabled(), 'Kruschke 3V 7/12 : case « Aligner la base » disponible')
    base('3', 'Kruschke', 'Pentad', '7/12', True)
    s = T('#baseStruts')
    check(all(x in s for x in ['824.27', '955.73', '1053.72', '1102.64']) and s == ref, 'référence 3V 7/12 alignée : struts identiques (30/35/80/20)')
    check(T('#statFaces') == '105', 'référence : 105 faces')
    base('3', 'Kruschke', 'Pentad', '3/4', False)
    check('non' in T('#baseKpis'), '3V Kruschke 3/4 sans alignement : base non plate')
    base('3', 'Kruschke', 'Pentad', '3/4', True)
    k = T('#baseKpis')
    check('Base plate' in k and '✓ oui' in k, '3V Kruschke 3/4 aligné : base plate')
    base('3', 'Kruschke', 'Cross', '7/12', False)
    pg.click('#paramAlign'); pg.wait_for_timeout(1200)
    w = T('#baseWarn')
    check('refusé' in w and not pg.is_checked('#paramAlign'), '3V Kruschke Cross 7/12 : alignement refusé, case décochée')
    check(T('#statFaces') != '–', 'dôme quand même calculé sans alignement')
    base('3', 'Kruschke', 'Pentad', '7/12', False)
    check(T('#baseWarn').strip() == '', 'message effacé au calcul suivant')
    check(not errs, 'aucune erreur JavaScript' + (' : ' + '; '.join(errs[:3]) if errs else ''))
    b.close()
print('RÉSULTAT :', 'OK' if not fails else 'ÉCHEC (' + str(len(fails)) + ')')
sys.exit(1 if fails else 0)
